/**
 * Local Storage Persistence Helpers for Centralized Catalogue
 */
const STORAGE_KEY = 'easylife_central_products';

export function getStoredCatalogue(): Product[] {
  try {
    const data = localStorage.getItem(STORAGE_KEY);
    if (!data) return INITIAL_PRODUCTS;
    const parsed: Product[] = JSON.parse(data);
    if (Array.isArray(parsed) && parsed.length > 0) {
      // Ensure prices and stock are strictly numbers and computed properties
      return parsed.map((p) => ({
        ...p,
        originalPrice: Number(p.originalPrice) || 0,
        salePrice: Number(p.salePrice) || 0,
        stock: Number(p.stock) || 0,
        availability: getStockStatus(Number(p.stock) || 0),
        reviews: p.reviews ?? p.reviewCount ?? 0,
        reviewCount: p.reviewCount ?? p.reviews ?? 0
      }));
    }
  } catch (e) {
    console.error('Failed to load catalogue from localStorage', e);
  }
  return INITIAL_PRODUCTS;
}

export function saveStoredCatalogue(products: Product[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(products));
  } catch (e) {
    console.error('Failed to save catalogue to localStorage', e);
  }
}

export function resetStoredCatalogue(): Product[] {
  try {
    localStorage.removeItem(STORAGE_KEY);
  } catch (e) {
    console.error('Failed to reset catalogue in localStorage', e);
  }
  return INITIAL_PRODUCTS;
}
